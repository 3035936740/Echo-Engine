"""Regenerate named snapshot fields after changing a snapshot struct.
Only Python stdlib is needed; this is a maintainer tool, not a build/runtime dependency.
Generated structured bindings make newly added/removed fields a compile error until regenerated.
"""
from pathlib import Path
import re

root = Path(__file__).resolve().parents[1]
headers = ["animation_state.hpp", "object_state.hpp", "world.hpp"]
skip = {"FixedList", "Text"}

def split_top(text, delimiter):
    result, start, depth = [], 0, 0
    for i, c in enumerate(text):
        if c in "{[<": depth += 1
        elif c in "}]>": depth -= 1
        elif c == delimiter and depth == 0:
            result.append(text[start:i].strip())
            start = i + 1
    if text[start:].strip(): result.append(text[start:].strip())
    return result

schemas = []
for name in headers:
    source = (root / "echo_engine/include/echo" / name).read_text(encoding="utf-8-sig")
    source = re.sub(r"/\*.*?\*/|//[^\n]*", "", source, flags=re.S)
    for match in re.finditer(r"\bstruct\s+(\w+)\s*\{", source):
        kind = match[1]
        if kind in skip: continue
        pos, depth = match.end(), 1
        while depth:
            if source[pos] == "{": depth += 1
            elif source[pos] == "}": depth -= 1
            pos += 1
        fields = []
        for stmt in split_top(source[match.end():pos-1], ";"):
            if "(" in stmt: continue  # methods; no snapshot initializer calls are supported
            depth = 0
            boundary = None
            for i, c in enumerate(stmt):
                if c == "<": depth += 1
                elif c == ">": depth -= 1
                elif c.isspace() and depth == 0:
                    boundary = i
                    break
            if boundary is None: raise ValueError(f"Unsupported field: {kind}: {stmt}")
            for declarator in split_top(stmt[boundary:].strip(), ","):
                field = re.fullmatch(r"(\w+)\s*(?:\{.*\}|=.*)?", declarator, flags=re.S)
                if not field: raise ValueError(f"Unsupported declaration: {kind}: {declarator}")
                fields.append(field[1])
        if not fields: raise ValueError(f"No fields in {kind}")
        schemas.append((kind, fields))

out = ["// Generated by tools/generate_snapshot_fields.py. Do not edit by hand.",
       "// Structured bindings deliberately fail compilation when a snapshot struct changes.",
       "#pragma once", '#include "world.hpp"', "#include <array>", "#include <string_view>",
       "namespace echo::snapshot_detail {"]
for kind, fields in schemas:
    out += [f"template <class F> void members(const {kind}& a, const {kind}& b, F&& f) {{",
            "    [[maybe_unused]] const auto& [" + ", ".join("m"+str(i) for i in range(len(fields))) + "] = a;"]
    for field in fields:
        out.append(f'    f("{field}", a.{field}, b.{field});')
    out.append("}")
out.append("} // namespace echo::snapshot_detail")
destination = root / "echo_engine/include/echo/snapshot_fields.hpp"
destination.write_text("\n".join(out)+"\n", encoding="utf-8")
print(f"Generated {len(schemas)} structs / {sum(len(f) for _,f in schemas)} named fields")
